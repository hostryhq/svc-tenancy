// Command gen derives, from the api-specs OpenAPI document and permission catalogue,
// the per-operation authorisation table (internal/gen/policies.gen.go) and the permission
// catalogue JSON (internal/gen/catalogue.json). It is run by `make gen` after oapi-codegen.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type opDoc struct {
	OperationID string           `yaml:"operationId"`
	Permission  string           `yaml:"x-permission"`
	StepUp      bool             `yaml:"x-step-up"`
	Callers     []string         `yaml:"x-service-callers"`
	VendorAudit string           `yaml:"x-vendor-audit"`
	VendorClass string           `yaml:"x-vendor-class"`
	Flag        string           `yaml:"x-feature-flag"`
	Outlet      bool             `yaml:"x-outlet-scoped"`
	Security    []map[string]any `yaml:"security"`
}

type specDoc struct {
	Paths map[string]map[string]yaml.Node `yaml:"paths"`
}

type permDoc struct {
	Permissions []struct {
		Key   string   `yaml:"key"`
		Svc   string   `yaml:"service"`
		Flags []string `yaml:"flags"`
	} `yaml:"permissions"`
}

type catPerm struct {
	Name            string `json:"name"`
	Owner           string `json:"owner"`
	Sensitive       bool   `json:"sensitive,omitempty"`
	StrongOnly      bool   `json:"strong_only,omitempty"`
	SupportViewable bool   `json:"support_viewable,omitempty"`
	SupportActable  bool   `json:"support_actable,omitempty"`
	OwnerGrant      bool   `json:"owner_grant,omitempty"`
}

func main() {
	specPath := flag.String("spec", "", "tenancy openapi.yaml")
	permPath := flag.String("permissions", "", "common/permissions.yaml")
	outDir := flag.String("out", "internal/gen", "output directory")
	flag.Parse()
	if err := run(*specPath, *permPath, *outDir); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(specPath, permPath, outDir string) error {
	sb, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}
	var spec specDoc
	if err := yaml.Unmarshal(sb, &spec); err != nil {
		return err
	}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/gen from api-specs; DO NOT EDIT.\n\npackage gen\n\n")
	buf.WriteString("// OpPolicy is the authorisation declaration of one operation, read from the OpenAPI extensions.\n")
	buf.WriteString("type OpPolicy struct {\n\tOperationID string\n\tPermission string\n\tStepUp bool\n\tInternal bool\n\tVendorRealm bool\n\tServiceOnly bool\n\tCallers []string\n\tVendorAuditNone bool\n\tDirectoryClass bool\n\tFeatureFlag string\n\tOutletScoped bool\n}\n\n")
	buf.WriteString("// Policies maps \"METHOD /path\" (net/http mux pattern) to the operation's policy.\nvar Policies = map[string]OpPolicy{\n")
	var keys []string
	pol := map[string]opDoc{}
	for path, item := range spec.Paths {
		for method, node := range item {
			switch method {
			case "get", "put", "post", "delete", "patch":
			default:
				continue
			}
			var op opDoc
			if err := node.Decode(&op); err != nil {
				return fmt.Errorf("%s %s: %w", method, path, err)
			}
			k := strings.ToUpper(method) + " " + path
			keys = append(keys, k)
			pol[k] = op
		}
	}
	sort.Strings(keys)
	for _, k := range keys {
		op := pol[k]
		internal := strings.Contains(k, " /internal/v1/")
		vendor := false
		for _, s := range op.Security {
			if _, ok := s["vendorBearerAuth"]; ok {
				vendor = true
			}
		}
		service := internal && !vendor
		perm := op.Permission
		if service {
			perm = ""
		}
		fmt.Fprintf(&buf, "\t%q: {OperationID: %q, Permission: %q, StepUp: %v, Internal: %v, VendorRealm: %v, ServiceOnly: %v, Callers: %#v, VendorAuditNone: %v, DirectoryClass: %v, FeatureFlag: %q, OutletScoped: %v},\n",
			k, op.OperationID, perm, op.StepUp, internal, vendor, service, op.Callers, op.VendorAudit == "none", op.VendorClass == "directory", op.Flag, op.Outlet)
	}
	buf.WriteString("}\n")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	if err := os.WriteFile(outDir+"/policies.gen.go", src, 0o644); err != nil {
		return err
	}

	pb, err := os.ReadFile(permPath)
	if err != nil {
		return err
	}
	var pd permDoc
	if err := yaml.Unmarshal(pb, &pd); err != nil {
		return err
	}
	var cat []catPerm
	for _, p := range pd.Permissions {
		c := catPerm{Name: p.Key, Owner: p.Svc}
		for _, f := range p.Flags {
			switch f {
			case "sensitive":
				c.Sensitive = true
			case "strong_only":
				c.StrongOnly = true
			case "support_viewable":
				c.SupportViewable = true
			case "support_actable":
				c.SupportActable = true
			case "owner_grant":
				c.OwnerGrant = true
			}
		}
		cat = append(cat, c)
	}
	cj, err := json.MarshalIndent(cat, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(outDir+"/catalogue.json", append(cj, '\n'), 0o644)
}
